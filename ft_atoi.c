int	ft_atoi(const char *nptr)
{
	int	i;
	int	digit;
	int	sign;

	digit = 0;
	sign = 1;
	i = 0;
	while ((nptr[i] >= 9 && nptr[i] <= 13) || nptr[i] == 32)
	{
		i++;
	}
	if (nptr[i] == '-')
	{
		sign *= -1;
		i++;
	}
	else if (nptr[i] == '+')
		i++;
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		digit = (digit * 10) + (nptr[i] - '0');
		i++;
	}
	return (digit * sign);
}
